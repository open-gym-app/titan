/**
 * The demo dataset the store screenshots are taken from (#46): one export per listing language
 * under `tools/demo/`, generated by [DemoHistory] over the real graph.
 *
 * ### Two modes
 *
 * - **Checking**, the default, and what `make test` runs: the generator is run again and its
 *   export must equal the committed file byte for byte, and the committed file must restore
 *   through the real import. A change to the schema, the seed, the default templates or any
 *   engine in the post-session cascade that moves a single row fails here, with the command
 *   that regenerates the files, rather than leaving the screenshots to be taken from a file
 *   that no longer describes what the app would have written.
 * - **Recording** — `make demo-data`, which sets `titan.storeAssets.record` — writes the files.
 *
 * ### One file per language
 *
 * The seed names the default templates in the device's language when the database is created,
 * and an export carries those names as the user's own rows. A French listing taken from the
 * English file would show "Push" and "Legs" on a French screen; so each language gets the
 * export a phone in that language would have written.
 */
@HiltAndroidTest
@RunWith(RobolectricTestRunner::class)
@Config(application = HiltTestApplication::class)
class DemoDatasetTest {

    @get:Rule
    val hilt = HiltAndroidRule(this)

    @Inject lateinit var exercises: ExerciseRepository

    @Inject lateinit var templates: TemplateRepository

    @Inject lateinit var sessions: SessionRepository

    @Inject lateinit var bodyMeasurements: BodyMeasurementRepository

    @Inject lateinit var preferences: UserPreferencesRepository

    @Inject lateinit var backup: BackupRepository

    @Inject lateinit var personalRecords: PersonalRecordRepository

    @Inject lateinit var gamification: GamificationRepository

    @Inject lateinit var collectedItems: CollectedItemRepository

    @Inject lateinit var detectPersonalRecords: PrDetectionUseCase

    @Inject lateinit var awardXp: AwardXpUseCase

    @Inject lateinit var triggerAchievements: AchievementTriggerUseCase

    @Inject lateinit var completeQuests: QuestCompletionUseCase

    @Inject lateinit var nextLoad: NextLoadUseCase

    @Inject lateinit var restore: ImportUseCase

    @Before
    fun setUp() {
        hilt.inject()
    }

    @Test
    @Config(qualifiers = "en-rUS")
    fun `the English demo export is what the generator writes`() = generate(StoreLocale.EN_US)

    @Test
    @Config(qualifiers = "fr-rFR")
    fun `the French demo export is what the generator writes`() = generate(StoreLocale.FR_FR)

    @Test
    @Config(qualifiers = "es-rES")
    fun `the Spanish demo export is what the generator writes`() = generate(StoreLocale.ES_ES)

    @Test
    @Config(qualifiers = "pt-rBR")
    fun `the Portuguese demo export is what the generator writes`() = generate(StoreLocale.PT_BR)

    private fun generate(locale: StoreLocale) =
        runBlocking {
            val context = ApplicationProvider.getApplicationContext<Context>()
            val random = Random(StoreAssets.DEMO_SEED)

            preferences.setOnboardingCompleted(true)
            preferences.setTrainingGoal(TrainingGoal.HYPERTROPHY)
            preferences.setFitnessLevel(FitnessLevel.INTERMEDIATE)

            DemoHistory(
                exercises = exercises,
                templates = templates,
                sessions = sessions,
                bodyMeasurements = bodyMeasurements,
                nextLoad = nextLoad,
                pipeline = pipeline(random),
                random = random,
            ).write(
                templateNames = listOf(
                    context.getString(DataR.string.default_template_push),
                    context.getString(DataR.string.default_template_pull),
                    context.getString(DataR.string.default_template_legs),
                ),
                repRange = preferences.observe().first().repRange,
                lastTrainingDay = StoreAssets.LAST_TRAINING_DAY,
            )

            val generated = export()
            val file = StoreAssets.demoFile(locale)
            if (StoreAssets.isRecording) {
                file.parentFile?.mkdirs()
                file.writeText(generated)
                return@runBlocking
            }

            assertTrue("${file.path} is missing — run `make demo-data`", file.isFile)
            // Not assertEquals on the text: a megabyte-long single line is not a failure message
            // anybody can read.
            assertTrue(
                "${file.name} is not what the generator writes any more — run `make demo-data`, " +
                    "then `make store-screenshots`",
                generated == file.readText(),
            )

            val restored = restore(ImportSource { file.inputStream() }).last()
            assertTrue("${file.name} does not restore: $restored", restored is ImportProgress.Complete)
            assertEquals(DemoHistory.SESSION_COUNT, sessions.countFinished())
        }

    /**
     * The production cascade, with loot rolled from [random] rather than from the system's
     * source — the one engine in it that draws at random, and the one thing standing between
     * the generator and a reproducible file.
     */
    private fun pipeline(random: Random) =
        SessionCompletionPipeline(
            detectPersonalRecords = detectPersonalRecords,
            awardXp = awardXp,
            triggerAchievements = triggerAchievements,
            completeQuests = completeQuests,
            rollLoot = LootRollUseCase(
                dropTable = DropTableEvaluator(random = RandomSource { bound -> random.nextInt(bound) }),
                collectedItemRepository = collectedItems,
                gamificationRepository = gamification,
            ),
            sessionRepository = sessions,
            personalRecordRepository = personalRecords,
            gamificationRepository = gamification,
        )

    private suspend fun export(): String {
        val text = StringBuilder()
        ExportUseCase(
            backupRepository = backup,
            userPreferencesRepository = preferences,
            clock = Clock { StoreAssets.DEMO_NOW },
        )(sink = { chunk -> text.append(chunk) }, appVersion = StoreAssets.DEMO_APP_VERSION).last()
        return text.toString()
    }
}
