/**
 * Seeds **every one of the nineteen tables** through the backup DAO, so a round trip has
 * something to lose in each of them.
 *
 * A fixture that left three tables empty would let an export that silently dropped them pass
 * every assertion about the sixteen it did carry — and the tables most likely to be forgotten
 * are exactly the ones no screen reads: the two claim tables, `quest_completion`,
 * `exercise_tag`. [BackupRoundTripTest] asserts against [BackupTable.entries] rather than
 * against a list written here, so a table added to the schema and not seeded here fails rather
 * than quietly dropping out of the coverage.
 *
 * Rows are written with **explicit ids** rather than autogenerated ones, because that is what
 * an import does and what the round trip has to reproduce: the document's ids are the only ids
 * afterwards, so a fixture that let SQLite number the rows would be testing a different write
 * path from the one under test.
 */
suspend fun TitanDatabase.seedEveryTable() {
    val dao = backupDao()

    dao.insertMuscleGroups(
        listOf(
            muscleGroup(name = "CHEST").copy(id = 1, icon = "chest.webp"),
            muscleGroup(name = "TRICEPS").copy(id = 2),
        ),
    )
    dao.insertTags(
        listOf(
            tag(name = "PUSH", isSystem = true).copy(id = 1, color = "#ff0000"),
            tag(name = "favourites").copy(id = 2),
        ),
    )
    dao.insertExercises(
        listOf(
            exercise(name = "Bench Press").copy(
                id = 1,
                discipline = "POWERLIFTING",
                mechanicType = "COMPOUND",
                difficultyLevel = "INTERMEDIATE",
                defaultRest = 180,
                notes = "elbows in",
                instructions = "Lie on the bench…",
                icon = "bench.webp",
            ),
            // Every optional column left null, so the round trip has a row that must come back
            // with nulls rather than with the defaults a re-insert would have written.
            exercise(name = "Sled Push", equipmentType = "OTHER").copy(id = 2, isCustom = true),
        ),
    )
    dao.insertExerciseMuscleGroups(
        listOf(
            exerciseMuscleGroup(exerciseId = 1, muscleGroupId = 1, isPrimary = true),
            exerciseMuscleGroup(exerciseId = 1, muscleGroupId = 2, isPrimary = false),
        ),
    )
    dao.insertExerciseTags(listOf(ExerciseTagEntity(exerciseId = 1, tagId = 1)))

    seedTemplates()
    seedHistoryForBackup()
    seedProgressAndSpoils()
}

