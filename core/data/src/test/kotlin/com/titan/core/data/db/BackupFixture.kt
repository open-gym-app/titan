/** Every row of [table], as raw column-to-value maps, for an assertion that names no entity type. */
fun TitanDatabase.dumpTable(table: BackupTable): List<Map<String, String?>> =
    query("SELECT * FROM `${table.tableName}`", emptyArray()).use { cursor ->
        buildList {
            while (cursor.moveToNext()) {
                add(
                    (0 until cursor.columnCount).associate { column ->
                        cursor.getColumnName(column) to if (cursor.isNull(column)) null else cursor.getString(column)
                    },
                )
            }
        }
    }

/** The whole database as raw rows, table by table — what "byte-identical to before" is asserted against. */
fun TitanDatabase.dumpEverything(): Map<BackupTable, List<Map<String, String?>>> =
    BackupTable.entries.associateWith { dumpTable(it) }

