package com.titan.core.data.db.entity

import androidx.room.ColumnInfo
import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Index
import androidx.room.PrimaryKey

/**
 * One collectible that actually dropped: what it was, what dropped it, and when.
 *
 * The catalogue is not a table. Which collectibles exist is data in `:core:domain` (#107), the
 * same call [AchievementEntity] and [QuestCompletionEntity] both make, so adding one is a line
 * there and no schema change at all. A row here means a drop happened.
 *
 * ### Keyed by its own rowid, and that is the whole point
 *
 * [AchievementEntity] is keyed by the domain's id *because* an unlock happens once: the
 * uniqueness is the contract, and making the natural key the primary key is what lets its write
 * be a single `INSERT OR IGNORE`. This table wants the opposite. A collectible can drop again —
 * next week, or twice in one month — and a user who has pulled three of something holds three
 * of them, so a second drop must be a second row rather than an ignored write. Keying on
 * `collectible_id` would silently collapse the inventory into a set, which is precisely the
 * difference between the two tables.
 *
 * The consequence is that nothing here is idempotent, and nothing is meant to be: what stops a
 * re-entered cascade rolling twice is a fence over the *roll* (#171), not a unique index over
 * its result. A fence here could only ever refuse the second legitimate drop as well.
 *
 * ### And an index on `acquired_at`
 *
 * The one read orders by it and takes the newest few. Without the index that is a full scan and
 * a sort over a table that grows for the life of an install and never shrinks — see
 * [BodyMeasurementEntity], whose log is indexed for the same read shape.
 *
 * @property id the local rowid, autogenerated, and the only thing that identifies a drop.
 * @property collectibleId the catalogue's stable key for what dropped. Part of the storage
 *   contract: renaming one orphans every drop already written under the old spelling. A value
 *   this build does not recognise is a drop from a newer version rather than a corrupt row, and
 *   a restore must preserve it — `achievement`'s rule, verbatim.
 * @property source the stable key of the trigger that produced the drop, stored as it was
 *   written. Not decoded through [com.titan.core.data.mapper.decodeEnum] like the enum-valued
 *   columns are: the trigger taxonomy lives in the drop engine and can grow, and this column
 *   carries a newer build's value back out unchanged rather than reading it as null.
 *
 *   It is on the row rather than looked up from the collectible for the same reason: a build
 *   that does not know the collectible still has to be able to say where its drop came from.
 * @property acquiredAt when the drop was **earned** — the triggering event's own timestamp, in
 *   epoch milliseconds, not the moment the row was written, so a cascade retried an hour later
 *   does not date the drop to the retry.
 */
@Entity(
    tableName = "collected_item",
    foreignKeys = [
        ForeignKey(
            entity = WorkoutSessionEntity::class,
            parentColumns = ["id"],
            childColumns = ["session_id"],
            onDelete = ForeignKey.SET_NULL,
        ),
    ],
    // observeRecent() orders by acquired_at DESC and takes the newest few; index it so that
    // read is not a full scan plus a sort over an ever-growing table. session_id is indexed
    // because it is a foreign key: a session's delete looks its drops up by it.
    indices = [Index("acquired_at"), Index("session_id")],
)
data class CollectedItemEntity(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0,
    @ColumnInfo(name = "collectible_id")
    val collectibleId: String,
    @ColumnInfo(name = "source")
    val source: String,
    @ColumnInfo(name = "acquired_at")
    val acquiredAt: Long,
    /**
     * The session whose finish dropped this, so a screen can say "from Push Day, Nov 12". Null for
     * a drop from before the column existed, and for one whose session was deleted since: the
     * drop happened, so deleting the session keeps it (`SET NULL`).
     */
    @ColumnInfo(name = "session_id")
    val sessionId: Long? = null,
)
