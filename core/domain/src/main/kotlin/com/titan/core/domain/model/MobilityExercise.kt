package com.titan.core.domain.model

/**
 * A catalogue movement a warm-up or a cool-down can be built from: an exercise from one of the
 * two mobility disciplines, the muscles it moves, and which half of the session it belongs to.
 *
 * The seed holds 123 [Discipline.STRETCHING] movements and 61 [Discipline.PLYOMETRICS] ones,
 * every one of them with muscle links, and until #214 nothing read them as a group. This is
 * that group, in the shape [com.titan.core.domain.warmup.WarmupPlanner] picks from.
 *
 * ### Primary muscles only
 *
 * A stretch is *for* the muscle it lengthens. Its secondary links are the ones that happen to
 * be under tension while it does, and matching on them would offer a hamstring stretch to a
 * lifter who trained their calves. So this carries the prime movers and drops the rest — the
 * one place in the app where a secondary link is not worth reading.
 *
 * Plural, though the seed guarantees exactly one primary per exercise (see PERSISTENCE.md),
 * because a user-authored exercise is under no such guarantee and an empty set is the honest
 * answer for one with no links at all: it simply never matches.
 *
 * @property exercise the catalogue row, as the card draws it.
 * @property primaryMuscleGroupIds the `muscle_group` ids it moves as the prime mover.
 * @property isDynamic whether it travels through a range rather than holding a position — the
 *   `DYNAMIC` system tag, which the seed generator derives from the upstream `category` and
 *   `force` fields. **This is what splits a warm-up from a cool-down**: dynamic movements
 *   before the work, static ones after it, and nothing appears in both.
 */
data class MobilityExercise(
    val exercise: Exercise,
    val primaryMuscleGroupIds: Set<Long>,
    val isDynamic: Boolean,
) {

    companion object {

        /**
         * The name of the `DYNAMIC` tag row, as the seed writes it.
         *
         * A constant rather than a literal in the DAO's SQL, because the tag taxonomy is
         * generated by `tools/seed/generate_seed.py` and this is the one name Kotlin has to
         * agree with it about.
         */
        const val DYNAMIC_TAG: String = "DYNAMIC"
    }
}
