package com.titan.core.domain.model

/**
 * How an exercise reads how fast it was done: a pace per kilometre or mile, a pace per hundred
 * metres or yards, or a speed.
 *
 * Runners and walkers think in minutes per kilometre, swimmers in minutes per hundred metres and
 * cyclists in kilometres an hour, and the one [PrType.BEST_PACE] record is shown in whichever the
 * exercise calls for. A display choice and nothing else: the record, its comparison and its
 * storage are the same for all three — see [PrType.BEST_PACE].
 *
 * ### Carried by two system tags
 *
 * [Discipline] has only `CARDIO` for every one of these, so it cannot choose. The seed generator
 * tags the cycling, rowing and skating movements [SPEED_TAG] and the swims [SWIM_TAG], in the way
 * it tags a mobility movement `DYNAMIC`; an exercise with neither reads a pace per kilometre or
 * mile. A user's own exercise can carry either tag, since a tag is a row like any other.
 *
 * Rowing is a [SPEED] on purpose, although rowers often quote a split per 500 m: a fourth style
 * for one movement would be a fourth unit to format, compare and translate, and km/h is the
 * reading a rower's best shares with every other machine in the gym.
 */
enum class PaceStyle {
    /** Time per kilometre or per mile: `5:27 /km`. */
    PACE,

    /** Time per hundred metres or per hundred yards: `1:45 /100 m`. */
    SWIM_PACE,

    /** Distance per hour: `30.0 km/h`. */
    SPEED,
    ;

    companion object {

        /**
         * The names of the `tag` rows that choose a style, as the seed writes them.
         *
         * Constants rather than literals in the DAO, because the tag taxonomy is generated by
         * `tools/seed/generate_seed.py` and these are the names Kotlin has to agree with it about
         * — the same arrangement as [MobilityExercise.DYNAMIC_TAG].
         */
        const val SPEED_TAG: String = "SPEED"
        const val SWIM_TAG: String = "SWIM"

        /** Both tag names, for a query that reads only the rows that matter here. */
        val TAG_NAMES: List<String> = listOf(SPEED_TAG, SWIM_TAG)

        /**
         * The style an exercise carrying [tagNames] reads in.
         *
         * [SPEED_TAG] wins over [SWIM_TAG] if an exercise somehow has both, because a speed is
         * the reading somebody had to ask for — no seeded row carries the pair, and a user who
         * tagged their own exercise both ways is better served by the explicit choice than by a
         * pool length.
         */
        fun of(tagNames: Collection<String>): PaceStyle =
            when {
                SPEED_TAG in tagNames -> SPEED
                SWIM_TAG in tagNames -> SWIM_PACE
                else -> PACE
            }
    }
}
